/**
 * توليد تعليمات النظام (System Prompt) الخاصة بكل مستوى دراسي
 * لضمان إنتاج مذكرات بيداغوجية رسمية ودقيقة بنسبة 100% وفق منهاج الجيل الثاني
 */
