  // توجيهات مرنة حسب المستوى؛ لا تُفرض عناصر علمية إلا إذا كانت مرتبطة بالمورد الفعلي.
  const levelSpecificInstructions: Record<GradeLevel, string> = {
    '1AM': '- استخدم التجارب والكواشف فقط عندما يقتضيها المورد الفعلي ومصادره الرسمية، مع السلامة المدرسية.',
    '2AM': '- أدرج الجداول أو المقارنات أو الحسابات فقط عندما تخدم المورد الفعلي وتكون مثبتة أو مناسبة له.',
    '3AM': '- أدرج المصطلحات والرسومات العلمية المرتبطة بالمورد فقط، ولا تفرض لغة أو قائمة مصطلحات غير موجودة في المصدر.',
    '4AM': '- استخدم شبكة معايير BEM فقط عند وجود وضعية إدماجية/تقويم يستدعيها، ولا تضفها آلياً لكل حصة.'
  };

  const libraryGuidance = modelSections.length ? `
نموذج المكتبة الاسترشادي المحدد من الأستاذ يحتوي على الأقسام التالية: ${modelSections.join('، ')}. استخدمه كهيكل تنظيمي فقط، ولا تعتبره مصدراً رسمياً للمحتوى.
` : '';

