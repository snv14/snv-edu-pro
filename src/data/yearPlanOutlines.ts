export function getYearPlanTermPages(planId: string, term: string): number[] {
  const range = TERM_PAGE_RANGES[planId]?.[Number(term) - 1];
  return range ? Array.from({ length: range[1] - range[0] + 1 }, (_, i) => range[0] + i) : [];
}

