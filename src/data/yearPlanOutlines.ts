export function getYearPlanOutline(level: YearLevel, planId: string): YearPlanUnit[] {
  if (planId !== `annualPlan2023_${level}` && planId !== `learningPlan${level}`) return [];
  return (YEAR_PLAN_OUTLINES[planId] || []).map((unit, index) => ({ ...unit, weeksLabel: SOURCE_WEEK_LABELS[planId]?.[index] }));
}
