export function getTeacherGuide1amSource() {
  return getYearPlans('1am').find(plan => plan.id === 'annualPlan2023_1am')!;
}

export function filterTeacherGuide1am(query = '') {
  const terms = normalizeSourceQuery(query).split(' ').filter(Boolean);
  return TEACHER_GUIDE_1AM_SEQUENCES.filter(sequence => {
    const text = normalizeSourceQuery([sequence.title, sequence.guidance, ...sequence.priorKnowledge, ...sequence.resources, ...sequence.indicators].join(' '));
    return terms.every(term => text.includes(term));
  });
}

export function getTeacherGuide1amLessons(lessons: LessonMemo[], query = '') {
  const terms = normalizeSourceQuery(query).split(' ').filter(Boolean);
  return lessons.filter(lesson => lesson.level === '1am' && terms.every(term => normalizeSourceQuery(JSON.stringify(lesson)).includes(term)));
}
